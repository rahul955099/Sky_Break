/**
 * Post-build step: writes Netlify `_redirects` and `_headers` into client/dist.
 *
 * Generated (rather than static in netlify.toml) because the backend address comes from an
 * environment variable, and Netlify config files cannot interpolate environment variables.
 *
 *   API_PROXY_ORIGIN  Recommended. Backend origin, e.g. https://skybreak-api.onrender.com
 *                     Netlify proxies /api, /uploads, /sitemap.xml and /robots.txt to it, so the
 *                     browser only ever talks to the site's own origin (first-party cookies).
 *   VITE_API_URL      Alternative. Full cross-origin API base, e.g. https://api.example.com/api
 *                     (requires COOKIE_SAMESITE=none on the backend — see docs/DEPLOYMENT.md).
 *
 * On Netlify (NETLIFY=true) the build fails if neither is set, instead of publishing a site
 * whose API calls can never succeed.
 */
import { writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dist = resolve(dirname(fileURLToPath(import.meta.url)), "../dist");
const onNetlify = process.env.NETLIFY === "true";
const fail = (msg) => {
  console.error(`\n✖ deploy config: ${msg}\n`);
  process.exit(1);
};

if (!existsSync(dist)) fail("client/dist not found — run vite build first");

function parseOrigin(name, value, { allowPath = false } = {}) {
  if (!value) return null;
  let url;
  try {
    url = new URL(value);
  } catch {
    fail(`${name} is not a valid URL: "${value}"`);
  }
  const local = ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname);
  if (onNetlify && local) fail(`${name} points to ${url.hostname} — a deployed site cannot reach your computer. Use the hosted backend URL.`);
  if (url.protocol !== "https:" && !local) fail(`${name} must use https:// (got ${url.protocol})`);
  if (!allowPath && url.pathname !== "/") fail(`${name} must be an origin only, without a path (e.g. https://skybreak-api.onrender.com)`);
  return url;
}

const proxy = parseOrigin("API_PROXY_ORIGIN", process.env.API_PROXY_ORIGIN?.trim());
const direct = parseOrigin("VITE_API_URL", process.env.VITE_API_URL?.trim(), { allowPath: true });

if (onNetlify && !proxy && !direct) {
  fail(
    "no backend configured. Set API_PROXY_ORIGIN (recommended) to your deployed Express API origin " +
      "in Netlify → Site configuration → Environment variables, then redeploy. See docs/DEPLOYMENT.md.",
  );
}
if (onNetlify && !process.env.VITE_PUBLIC_SITE_URL) {
  console.warn("⚠ deploy config: VITE_PUBLIC_SITE_URL is not set; canonical URLs will use the visitor's current origin.");
}

// ── _redirects ────────────────────────────────────────────────
const lines = ["# Generated by client/scripts/write-deploy-config.mjs — do not edit in dist."];
if (proxy) {
  const o = proxy.origin;
  lines.push(
    `/api/*        ${o}/api/:splat     200!`,
    `/uploads/*    ${o}/uploads/:splat 200!`,
    `/sitemap.xml  ${o}/sitemap.xml    200!`,
    `/robots.txt   ${o}/robots.txt     200!`,
  );
}
// SPA fallback: deep links such as /admin or /projects/<slug> load the app shell.
lines.push("/*            /index.html         200");
writeFileSync(resolve(dist, "_redirects"), lines.join("\n") + "\n");

// ── _headers ──────────────────────────────────────────────────
const extra = direct ? ` ${direct.origin}` : "";
const csp = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  `img-src 'self' data: blob: https://images.unsplash.com${extra}`,
  `connect-src 'self'${extra}`,
  "upgrade-insecure-requests",
].join("; ");
const headers = `# Generated by client/scripts/write-deploy-config.mjs — do not edit in dist.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/brand/*
  Cache-Control: public, max-age=86400
`;
writeFileSync(resolve(dist, "_headers"), headers);

const mode = proxy ? `proxy → ${proxy.origin}` : direct ? `direct → ${direct.href}` : "none (local build: /api is served by the Vite proxy or SERVE_CLIENT)";
console.log(`✔ deploy config written (_redirects, _headers) · API: ${mode}`);
